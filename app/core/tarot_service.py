    def _preprocess_cards(self, cards: list[str]) -> list[str]:
        """
        Обрабатывает список карт, добавляя пометку о перевернутых картах.
        
        Args:
            cards: Список карт Таро
            
        Returns:
            Обработанный список карт с пометками о перевернутых
        """
        processed_cards = []
        for card in cards:
            # Если карта заканчивается на *, значит она перевернута
            if card.endswith('*'):
                processed_cards.append(f"{card[:-1]} (перевернутая)")
            else:
                processed_cards.append(card)
        return processed_cards

    def _clean_interpretation(self, interpretation: str) -> str:
        """
        Удаляет ключ расклада, названия карт в скобках и другие технические детали из интерпретации.
        
        Args:
            interpretation: Сырая интерпретация от AI
            
        Returns:
            Очищенная интерпретация
        """
        # Удаляем строку с ключом расклада, если она есть
        interpretation = re.sub(r'Ключ расклада:\s*\[.*?\]', '', interpretation, flags=re.IGNORECASE)
        # Удаляем названия карт в скобках (например, "(Маг)", "(Императрица)")
        interpretation = re.sub(r'\([^)]*\)', '', interpretation)
        # Удаляем лишние пробелы и переносы строк
        interpretation = re.sub(r'\s+', ' ', interpretation).strip()
        return interpretation

